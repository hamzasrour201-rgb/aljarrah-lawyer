export function getRelatedArticles(currentSlug: string, locale: 'ar' | 'en', count = 3): Array<{ slug: string } & ArticleLocaleData> {
  return Object.entries(articles)
    .filter(([slug]) => slug !== currentSlug)
    .slice(0, count)
    .map(([slug, entry]) => ({ slug, ...entry[locale] }))
}
